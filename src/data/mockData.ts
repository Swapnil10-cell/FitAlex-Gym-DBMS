// Generate dynamic relative dates based on current execution time
const now = new Date();

const getOffsetDate = (daysOffset: number, hoursOffset: number = 0, minutesOffset: number = 0): string => {
  const d = new Date(now.getTime());
  d.setDate(d.getDate() + daysOffset);
  d.setHours(d.getHours() + hoursOffset);
  d.setMinutes(d.getMinutes() + minutesOffset);
  return d.toISOString();
};

